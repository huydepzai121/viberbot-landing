#!/usr/bin/env bash
# Fetch the newest ViberVN Bot installers with `gh` (run where you are logged in,
# never put a GitHub token on the VPS) and write them next to latest.json.
#
# Usage:
#   scripts/sync-downloads.sh
#   DEST=/opt/viberbot-landing/downloads scripts/sync-downloads.sh
#   TAG=v0.8.0 REMOTE=root@167.104.100.64:/opt/viberbot-landing/downloads scripts/sync-downloads.sh
#
# Env:
#   REPO    GitHub repo (default: huydepzai121/vibervn-bot)
#   TAG     Release tag; empty means the latest release
#   DEST    Local directory to write files into (default: <repo>/downloads)
#   REMOTE  Optional rsync destination after a successful local sync
#   KEEP_OLD  If 1, leave previous version files in DEST

set -euo pipefail

REPO="${REPO:-huydepzai121/vibervn-bot}"
TAG="${TAG:-}"
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
DEST="${DEST:-$ROOT/downloads}"
REMOTE="${REMOTE:-}"
KEEP_OLD="${KEEP_OLD:-0}"

if ! command -v gh >/dev/null 2>&1; then
  echo "gh is required (GitHub CLI). Authenticate on this machine, not on the VPS." >&2
  exit 1
fi
if ! command -v python3 >/dev/null 2>&1; then
  echo "python3 is required to write the manifest." >&2
  exit 1
fi

if [ -z "$TAG" ]; then
  TAG="$(gh release view -R "$REPO" --json tagName --jq .tagName)"
fi

echo "Syncing $REPO $TAG -> $DEST"

mkdir -p "$DEST"
tmp="$(mktemp -d "${TMPDIR:-/tmp}/vibervn-dl.XXXXXX")"
cleanup() { rm -rf "$tmp"; }
trap cleanup EXIT

gh release download "$TAG" -R "$REPO" -D "$tmp" --skip-existing

# Classify installer assets and write latest.json + nginx alias 302s.
python3 - "$tmp" "$DEST" "$TAG" "$KEEP_OLD" << 'PY'
import json, os, re, shutil, sys, hashlib

src, dest, tag, keep_old = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4] == "1"
version = tag[1:] if tag.startswith("v") else tag

# id, label, kind — first matching pattern wins
rules = [
    ("windows-cert", "Chứng chỉ ViberVN-signing.cer", r"^ViberVN-signing\.cer$", "cert", "windows", ""),
    ("windows", "Windows 11 (x64) .msix", r"win-x64\.msix$", "installer", "windows", "x64"),
    ("mac-arm64", "macOS Apple Silicon .dmg", r"mac-arm64\.dmg$", "installer", "macos", "arm64"),
    ("mac-x64", "macOS Intel .dmg", r"mac-x64\.dmg$", "installer", "macos", "x64"),
    ("mac-arm64-zip", "macOS Apple Silicon .zip", r"mac-arm64\.zip$", "archive", "macos", "arm64"),
    ("mac-x64-zip", "macOS Intel .zip", r"mac-x64\.zip$", "archive", "macos", "x64"),
    ("linux-x64", "Linux x86_64 .AppImage", r"linux-x86_64\.AppImage$", "installer", "linux", "x86_64"),
    ("linux-arm64", "Linux arm64 .AppImage", r"linux-arm64\.AppImage$", "installer", "linux", "arm64"),
]

def classify(name: str):
    for rid, label, pat, kind, platform, arch in rules:
        if re.search(pat, name, re.I):
            return rid, label, kind, platform, arch
    return None

published = None
# best-effort timestamp from source mtime
files_meta = []
copied = []
for name in sorted(os.listdir(src)):
    path = os.path.join(src, name)
    if not os.path.isfile(path):
        continue
    if name.endswith(".sha256"):
        continue
    info = classify(name)
    if not info:
        print(f"skip (not an installer): {name}")
        continue
    rid, label, kind, platform, arch = info
    dest_path = os.path.join(dest, name)
    shutil.copy2(path, dest_path)
    size = os.path.getsize(dest_path)
    copied.append(name)
    # sha256 if a sidecar exists, else leave empty (large files; avoid hashing unless needed)
    sha = ""
    sidecar = path + ".sha256"
    if os.path.isfile(sidecar):
        sha = open(sidecar).read().strip().split()[0]
    files_meta.append({
        "id": rid,
        "label": label,
        "file": name,
        "href": f"/downloads/{name}",
        "alias": f"/downloads/{rid}",
        "size": size,
        "sha256": sha,
        "platform": platform,
        "arch": arch,
        "kind": kind,
    })

if not files_meta:
    raise SystemExit("no installer assets found in the release")

# stable order: rules order
order = {rid: i for i, (rid, *_rest) in enumerate(rules)}
files_meta.sort(key=lambda f: order.get(f["id"], 99))

manifest = {
    "version": version,
    "tag": tag if tag.startswith("v") else f"v{version}",
    "files": files_meta,
}
with open(os.path.join(dest, "latest.json"), "w") as fh:
    json.dump(manifest, fh, indent=2, ensure_ascii=False)
    fh.write("\n")

alias_lines = [
    "# Generated by scripts/sync-downloads.sh — do not edit by hand.",
    "# Stable aliases 302 to the current installer filename.",
]
for f in files_meta:
    alias_lines.append(f"location = {f['alias']} {{ return 302 {f['href']}; }}")
with open(os.path.join(dest, "nginx-aliases.conf"), "w") as fh:
    fh.write("\n".join(alias_lines) + "\n")

if not keep_old:
    keep = {f["file"] for f in files_meta}
    keep.update({"latest.json", "nginx-aliases.conf", ".gitkeep"})
    for name in os.listdir(dest):
        if name in keep or name.startswith("."):
            continue
        path = os.path.join(dest, name)
        if os.path.isfile(path):
            print(f"remove old: {name}")
            os.remove(path)

print(f"wrote {len(files_meta)} files for v{version}:")
for f in files_meta:
    print(f"  {f['id']:16} {f['size']:12}  {f['file']}")
PY

if [ -n "$REMOTE" ]; then
  echo "rsync -> $REMOTE"
  rsync -a --info=progress2 \
    --exclude '.gitkeep' \
    "$DEST/" "$REMOTE/"
fi

echo "done."
